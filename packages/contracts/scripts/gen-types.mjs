// Generates src/generated/types.ts from schemas/drift.schema.json (deterministic).
import { readFileSync, writeFileSync } from "node:fs";
import { compile } from "json-schema-to-typescript";

const schema = JSON.parse(readFileSync(new URL("../schemas/drift.schema.json", import.meta.url)));
const names = Object.keys(schema.$defs);
const root = {
  title: "DriftContracts",
  type: "object",
  additionalProperties: false,
  $defs: schema.$defs,
  properties: Object.fromEntries(names.map((n) => [n, { $ref: `#/$defs/${n}` }])),
};
const ts = await compile(root, "DriftContracts", {
  bannerComment: "/* AUTO-GENERATED by `pnpm contracts:gen` from schemas/drift.schema.json. DO NOT EDIT. */",
  additionalProperties: false,
  unreachableDefinitions: true,
  format: true,
});
writeFileSync(new URL("../src/generated/types.ts", import.meta.url), ts);
console.log(`generated ${names.length} definitions`);
