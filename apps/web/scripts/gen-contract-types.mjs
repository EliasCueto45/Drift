// Generates TypeScript types from the canonical contract schema.
// packages/contracts/schemas/drift.schema.json stays the only source of truth;
// this file is a consumer-side binding owned by the frontend. `--check` fails if stale.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const schemaPath = fileURLToPath(new URL("../../../packages/contracts/schemas/drift.schema.json", import.meta.url));
const outPath = fileURLToPath(new URL("../src/lib/contracts/generated.ts", import.meta.url));

const schema = JSON.parse(await readFile(schemaPath, "utf8"));
const names = Object.keys(schema.$defs);

// json-schema-to-typescript predates draft 2020-12: map `prefixItems` to tuple `items`,
// and drop validation-only conditionals (if/then/allOf/not) that do not change the shape.
function normalize(node) {
  if (Array.isArray(node)) return node.map(normalize);
  if (!node || typeof node !== "object") return node;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (["if", "then", "else", "allOf", "not"].includes(key)) continue;
    if (key === "prefixItems") {
      out.items = normalize(value);
      out.additionalItems = false;
      continue;
    }
    out[key] = normalize(value);
  }
  return out;
}

// Give every definition a title so it is emitted under its own name.
const defs = Object.fromEntries(names.map((name) => [name, { title: name, ...normalize(schema.$defs[name]) }]));
const root = {
  title: "DriftContracts",
  type: "object",
  additionalProperties: false,
  $defs: defs,
  properties: Object.fromEntries(names.map((name) => [name, { $ref: `#/$defs/${name}` }])),
};

const banner = `/* Generated by apps/web/scripts/gen-contract-types.mjs from
 * packages/contracts/schemas/drift.schema.json. Do not edit; run \`npm run contracts:gen\`. */`;

let output = await compile(root, "DriftContracts", {
  bannerComment: banner,
  additionalProperties: false,
  strictIndexSignatures: true,
  unreachableDefinitions: true,
  format: true,
  style: { semi: true, singleQuote: false, printWidth: 110 },
});
output = output.replace(/\r\n/g, "\n");

if (process.argv.includes("--check")) {
  const current = await readFile(outPath, "utf8").catch(() => "");
  if (current !== output) {
    console.error("src/lib/contracts/generated.ts is stale. Run `npm run contracts:gen`.");
    process.exit(1);
  }
  console.log("Contract types match the canonical schema.");
} else {
  await writeFile(outPath, output);
  console.log(`Wrote ${names.length} contract definitions to src/lib/contracts/generated.ts`);
}
